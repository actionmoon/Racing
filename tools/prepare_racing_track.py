"""Emit exact captured track floats as a shared Lua module."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def lua(value):
    if isinstance(value, dict):
        return "{" + ",".join("[" + json.dumps(k) + "]=" + lua(v) for k, v in value.items()) + "}"
    if isinstance(value, list):
        return "{" + ",".join(lua(v) for v in value) + "}"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    return repr(value)


environments = {}
for map_id in ("city", "aegean", "egypt", "snow"):
    source = json.loads((ROOT / f"docs/reference/qqfeiche3d/tracks/{map_id}.json").read_text())
    track = source["track"]
    track["boostPads"] = source["boostPads"]
    track["id"] = map_id
    name = "TrackData" if map_id == "city" else "TrackData" + map_id.capitalize()
    target = ROOT / f"unity/Assets/RacingClone/Lua/Modules/{name}.lua"
    target.write_text("-- Generated by tools/prepare_racing_track.py; source coordinates.\nreturn " + lua(track) + "\n")
    print(target)
    environments[map_id] = source["config"]
(ROOT / "unity/Assets/RacingClone/Lua/Modules/RaceMapEnvironment.lua").write_text(
    "-- Generated map environment values from the reference.\nreturn " + lua(environments) + "\n")
